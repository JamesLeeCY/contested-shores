import { loadGameData } from '../../src/data/load';
import { loadMap } from '../../src/data/map';
import { scenarioById } from '../../src/data/scenarios';
import { enableAi } from '../../src/sim/ai';
import { step } from '../../src/sim/loop';
import { applyScenario } from '../../src/sim/scenario/setup';
import { World } from '../../src/sim/world';
const sc = scenarioById('ch1');
const w = new World(loadGameData(), loadMap(), { seed: 1 });
applyScenario(w, sc);
for (const [o, s] of Object.entries(sc.ai ?? {})) enableAi(w, o, s);
for (let t = 0; t < 20 * Number(process.argv[2] ?? 250); t++) step(w);
const ai = w.ext.ai.faction_voc;
console.log('voc plan', ai.plans, ai.planIdx, ai.stepIdx, JSON.stringify(ai.mem).slice(0, 300));
for (const e of w.all()) if (e.owner === 'faction_voc' && e.kind === 'unit' && (e.tag === 'sortie' || e.tag === 'sortie_boats' || e.tag === 'pedel')) console.log(e.id, e.type, e.x.toFixed(1), e.y.toFixed(1), JSON.stringify(e.order), 'inside', e.insideOf ?? '', 'cargo', e.cargo?.length ?? '', 'goal', e.goalX?.toFixed(1), e.goalY?.toFixed(1));
